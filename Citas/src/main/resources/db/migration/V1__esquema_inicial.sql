-- Esquema actual H2. Solo bases nuevas: sin IF NOT EXISTS ni baseline automatico.
create table usuario (
    id bigint generated by default as identity primary key,
    activo boolean not null,
    cedula varchar(255),
    contacto varchar(255),
    correo varchar(255),
    nombre varchar(255),
    password varchar(255),
    rol enum ('ADMIN','USUARIO'),
    token_recuperacion varchar(255),
    version_recuperacion bigint default 0 not null,
    constraint uk_usuario_cedula unique (cedula),
    constraint uk_usuario_correo unique (correo)
);
create table medico (
    id bigint generated by default as identity primary key,
    activo boolean not null,
    especialidad varchar(255),
    nombre varchar(255)
);
create table disponibilidad_medico (
    id bigint generated by default as identity primary key,
    fecha date not null,
    hora_fin time(0) not null,
    hora_inicio time(0) not null,
    medico_id bigint not null,
    constraint uk_disponibilidad_medico_horario unique (medico_id,fecha,hora_inicio,hora_fin),
    constraint fk_disponibilidad_medico foreign key (medico_id) references medico(id)
);
create table cita (
    id bigint generated by default as identity primary key,
    estado enum ('CANCELADA','CONFIRMADA','PENDIENTE') not null,
    fecha date not null,
    fecha_creacion timestamp(6) not null,
    hora_fin time(0) not null,
    hora_inicio time(0) not null,
    disponibilidad_id bigint not null,
    medico_id bigint not null,
    usuario_id bigint not null,
    constraint fk_cita_disponibilidad foreign key (disponibilidad_id) references disponibilidad_medico(id),
    constraint fk_cita_medico foreign key (medico_id) references medico(id),
    constraint fk_cita_usuario foreign key (usuario_id) references usuario(id)
);
create table token_recuperacion (
    id bigint generated by default as identity primary key,
    consumido_en timestamp(6) with time zone,
    hash varchar(64) not null,
    vence_en timestamp(6) with time zone not null,
    usuario_id bigint not null,
    constraint uk_token_hash unique (hash),
    constraint uk_token_usuario unique (usuario_id),
    constraint fk_token_usuario foreign key (usuario_id) references usuario(id)
);
